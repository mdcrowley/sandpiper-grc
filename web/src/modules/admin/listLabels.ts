/** A setting kept on each value of a list (in its `meta`), edited beside the value's name and color. */
export interface ListSetting {
  key: string;
  label: string;
  kind: 'number' | 'text' | 'choice';
  hint?: string;
  /** number: the smallest and largest whole number allowed. */
  min?: number;
  max?: number;
  /** choice: the options, stored value first. */
  options?: { value: string; label: string }[];
  /** choice: the value a value without the setting is treated as. */
  fallback?: string;
  required?: boolean;
  /** false: edited in the value's dialog only, not shown as a column (long text). */
  column?: boolean;
}

